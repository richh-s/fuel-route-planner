STATE_CODES_BY_NAME = {name.lower(): code for code, name in US_STATES.items()}


def normalize_state(value: str) -> str | None:
    """Return the two-letter code for a state code or full state name, or None."""
    cleaned = value.strip().replace(".", "")
    if cleaned.upper() in US_STATES:
        return cleaned.upper()
    return STATE_CODES_BY_NAME.get(cleaned.lower())
